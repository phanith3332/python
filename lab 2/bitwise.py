
p = 12
q = 10
print("p =", p, "Binary:", bin(p))
print("q =", q, "Binary:", bin(q))
print("p & q  =", p & q, "Binary:", bin(p & q))
print("p | q  =", p | q, "Binary:", bin(p | q))
print("p ^ q  =", p ^ q, "Binary:", bin(p ^ q))
print("~p     =", ~p, "Binary:", bin(~p))
print("p << 2 =", p << 2, "Binary:", bin(p << 2))
print("p >> 2 =", p >> 2, "Binary:", bin(p >> 2))

#output:p = 12 Binary: 0b1100
#q = 10 Binary: 0b1010
#p & q  = 8 Binary: 0b1000
#p | q  = 14 Binary: 0b1110
#p ^ q  = 6 Binary: 0b110
#~p     = -13 Binary: -0b1101
#p << 2 = 48 Binary: 0b110000
#p >> 2 = 3 Binary: 0b11